# and the appendix figure (fig:apdx-sim-privbudget, "Fig 18").
#
# Reviewer 3:
#  * "The triangle symbols for point estimates are poor. Perhaps a thick
#    horizontal line or a filled circle would be better. The value of the
#    estimate should be emphasised, triangles are distracting."
#    -> the confidential estimate is a thick horizontal bar (CONF_MARK =
#       "bar", the default) or a filled circle (CONF_MARK = "point"), in the
#       same black used for the confidential estimate in Fig 3, drawn
#       wider than the boxes so it cannot be mistaken for a median.
#    -> boxes are no longer coloured by model (the x-axis already identifies
#       the model); they take the method colour used in every other figure.
#    -> model labels are angled at 45 degrees and right-aligned, so they no
#       longer overlap.
#  * "Fig 18 is ... a mixture of Fig 6 and the third graph of Figure 5 on
#    Figure 6's scale." -> it is now generated by the same function as Figs 5
#    and 6 (GenM-1 and GenM-2 on a shared scale), so the three figures are
#    visibly the same design. Its caption should say what it is; the
#    with-outliers version of Fig 3 is produced in fig03_privbudget.R.
#
# Input: sim2_models.csv (model, method, rep, treff, conf_treff, ...).

CONF_MARK <- Sys.getenv("R3_CONF_MARK", "bar")  # "bar" or "point"

sim2 <- read_input("sim2_models.csv")
sim2$model <- factor(sim2$model, levels = intersect(MODEL_LEVELS, sim2$model))
conf <- unique(sim2[, c("model", "conf_treff")])
stopifnot(!anyDuplicated(conf$model))  # one confidential estimate per model

plot_treff <- function(methods, ncol = length(methods)) {
  d <- sim2[sim2$method %in% methods, ]
  d$method <- as_method(d$method)
  cf <- merge(conf, data.frame(method = factor(methods, levels = levels(d$method))))
  cf$what <- "Confidential estimate"

  conf_layer <- if (CONF_MARK == "point") {
    geom_point(data = cf, aes(model, conf_treff, shape = what),
               colour = COL_CONFIDENTIAL, size = 2.6, inherit.aes = FALSE)
  } else {
    geom_errorbar(data = cf, aes(model, ymin = conf_treff, ymax = conf_treff,
                                 linetype = what),
                  colour = COL_CONFIDENTIAL, width = 0.8, linewidth = 1.3,
                  inherit.aes = FALSE)
  }

  ggplot(d, aes(model, treff)) +
    geom_boxplot(aes(colour = method), width = 0.5, fill = "grey95",
                 outlier.size = 1, show.legend = FALSE) +
    conf_layer +
    facet_wrap(~ method, ncol = ncol) +
    scale_colour_manual(values = METHOD_COLORS) +
    scale_shape_manual(NULL, values = 19) +
    scale_linetype_manual(NULL, values = "solid") +
    labs(x = "Model", y = "Sanitized treatment effect") +
    theme_paper() +
    theme(axis.text.x = element_text(angle = 45, hjust = 1, vjust = 1),
          panel.grid.major.x = element_blank())
}

save_fig(plot_treff(c("MV Histogram", "Hybrid", "GenM-2")),
         "sim2_treff_ModelX_ThreeMethods_KeepOutliers", width = 8, height = 4)
save_fig(plot_treff("GenM-1"),
         "sim2_treff_ModelX_GenM1_KeepOutliers", width = 4, height = 4)
save_fig(plot_treff(c("GenM-1", "GenM-2")),
         "sim2_treff_ModelsX_OnlyDPMb_KeepOutliers", width = 6.5, height = 4)
